// Ждём первого кадра браузера.
// Это позволяет странице сначала начать отображаться.
requestAnimationFrame(() => {

    // Дополнительно ждём 1 секунду после первого кадра.
    // Так мы стараемся отделить первоначальную отрисовку
    // страницы от искусственной нагрузки.
    setTimeout(() => {

        // Запоминаем время начала эксперимента.
        const startTime = performance.now();

        // Продолжаем вычисления примерно 700 миллисекунд.
        // Пока выполняется этот цикл, главный поток занят.
        while (performance.now() - startTime < 700) {

            // Намеренно пустой цикл.
            // Он нужен только для создания вычислительной нагрузки.
        }

        // Сообщение для проверки в консоли браузера.
        console.log("Эксперимент № 1 завершён.");

    }, 1000);

});
